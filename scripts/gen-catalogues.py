#!/usr/bin/env python3
"""La table des catalogues du README, MESURÉE sur les dépôts publiés.

POURQUOI CE SCRIPT EXISTE

`templates/catalogues.yml` est ce que `dsoxlab catalog list` montre à un
apprenant. Il s'est périmé trois fois : le 2026-10-10 il annonçait trois
catalogues quand six existaient, le 2026-10-17 six quand douze existaient, et le
2026-11-14 le README annonçait 64 labs pour Kubernetes quand le dépôt publié en
portait 111, et ignorait huit catalogues publics. La cause était la même à
chaque fois : un chiffre écrit à la main, et un contrôle qui ne regardait que le
disque local, seulement quand le manifeste lui-même changeait.

CE QUI CHANGE

Le manifeste ne porte plus AUCUN chiffre : seulement l'identité d'un catalogue
(id, dépôt, descriptions). Le nombre de labs se mesure, à chaque génération,
sur la branche par défaut du dépôt PUBLIÉ, celui qu'un apprenant clone : le
nombre de `labs/**/lab.yaml` dans son arbre git, lu par l'API GitHub.

    (sans option) mesure et régénère la table des deux README.
    --check       mesure et sort en 1 si un README diffère de la mesure, ou si
                  un dépôt public porte des labs sans être dans le manifeste.

Un contrôle qui n'a pas pu regarder ne conclut jamais au vert : sans réseau, ou
sur un arbre git tronqué, le script sort en 2 et dit ce qu'il n'a pas pu lire.

Un jeton GitHub évite la limite de 60 requêtes par heure des appels anonymes :
`GH_TOKEN` ou `GITHUB_TOKEN`, sinon celui de `gh auth token` s'il est connecté.
Le jeton ne sert qu'à lire des dépôts PUBLICS : un dépôt privé n'est jamais
proposé, même si le jeton le voit.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

import yaml

RACINE = Path(__file__).resolve().parent.parent
MANIFESTE = RACINE / "src" / "dsoxlab" / "templates" / "catalogues.yml"
DEBUT, FIN = "<!-- CATALOGUES:START -->", "<!-- CATALOGUES:END -->"
CIBLES = {"README.md": "en", "README.fr.md": "fr"}
API = "https://api.github.com"
LAB = re.compile(r"labs/.+/lab\.yaml")

EN_TETES = {
    "en": ("Catalog", "Labs", "What it teaches"),
    "fr": ("Catalogue", "Labs", "Ce qu'il enseigne"),
}
PIED = {
    "en": "_{labs} labs across {n} catalogs, counted on the published repositories "
          "(`labs/**/lab.yaml` on their default branch). This table is generated by "
          "`scripts/gen-catalogues.py` from `src/dsoxlab/templates/catalogues.yml`, "
          "the manifest `dsoxlab catalog list` reads; no figure in it is written by "
          "hand._",
    "fr": "_{labs} labs dans {n} catalogues, comptés sur les dépôts publiés "
          "(`labs/**/lab.yaml` de leur branche par défaut). Cette table est générée "
          "par `scripts/gen-catalogues.py` depuis `src/dsoxlab/templates/catalogues.yml`, "
          "le manifeste que lit `dsoxlab catalog list` ; aucun chiffre n'y est écrit "
          "à la main._",
}


class NonMesurable(RuntimeError):
    """La question n'a pas pu être posée : réseau, limite d'appels, arbre tronqué."""


def _manifeste() -> list[dict[str, Any]]:
    donnees = yaml.safe_load(MANIFESTE.read_text(encoding="utf-8"))
    return list(donnees["catalogues"])


def _depot(url: str) -> tuple[str, str]:
    """`https://github.com/<proprio>/<nom>` → (proprio, nom)."""
    morceaux = url.rstrip("/").removesuffix(".git").split("/")
    return morceaux[-2], morceaux[-1]


# ── Lire GitHub ──────────────────────────────────────────────────────────────


def _jeton() -> str | None:
    for nom in ("GH_TOKEN", "GITHUB_TOKEN"):
        if os.environ.get(nom):
            return os.environ[nom]
    try:
        res = subprocess.run(["gh", "auth", "token"], capture_output=True, text=True,
                             check=False, timeout=15)
    except (OSError, subprocess.SubprocessError):
        return None
    if res.returncode != 0:
        return None
    return res.stdout.strip() or None


def _api(chemin: str, jeton: str | None) -> Any:
    requete = urllib.request.Request(f"{API}{chemin}", headers={  # noqa: S310 (API constante, https)
        "Accept": "application/vnd.github+json",
        "User-Agent": "dsoxlab-gen-catalogues",
        **({"Authorization": f"Bearer {jeton}"} if jeton else {}),
    })
    try:
        with urllib.request.urlopen(requete, timeout=30) as reponse:  # noqa: S310 (URL fixe, https)
            return json.load(reponse)
    except urllib.error.HTTPError as e:
        raise NonMesurable(f"{chemin} : HTTP {e.code}") from e
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        raise NonMesurable(f"{chemin} : {e}") from e


def _arbre(proprio: str, nom: str, branche: str, jeton: str | None) -> list[str]:
    try:
        arbre = _api(f"/repos/{proprio}/{nom}/git/trees/{branche}?recursive=1", jeton)
    except NonMesurable as e:
        # 409 : « Git Repository is empty ». Un dépôt créé mais jamais poussé
        # est une réponse, pas une panne : il ne publie aucun lab.
        if str(e).endswith("HTTP 409"):
            return []
        raise
    if arbre.get("truncated"):
        raise NonMesurable(f"{proprio}/{nom} : arbre git tronqué par l'API, compte impossible")
    return [e["path"] for e in arbre.get("tree", []) if e.get("type") == "blob"]


def _labs(chemins: list[str]) -> int:
    return sum(1 for c in chemins if LAB.fullmatch(c))


def _mesurer_le_manifeste(catalogues: list[dict[str, Any]], jeton: str | None) -> tuple[dict[str, int], list[str]]:
    """Le nombre de labs publiés de chaque entrée, et les entrées qui ne devraient plus y être."""
    comptes: dict[str, int] = {}
    ecarts: list[str] = []
    for entree in catalogues:
        proprio, nom = _depot(entree["depot"])
        infos = _api(f"/repos/{proprio}/{nom}", jeton)
        if infos.get("private"):
            ecarts.append(f"{nom} est PRIVÉ : le manifeste le propose à des apprenants qui ne peuvent pas le cloner")
            continue
        if infos.get("archived"):
            ecarts.append(f"{nom} est ARCHIVÉ : le manifeste propose un dépôt qui ne bouge plus")
        comptes[entree["depot"]] = _labs(_arbre(proprio, nom, infos["default_branch"], jeton))
    return comptes, ecarts


def _oublies(catalogues: list[dict[str, Any]], jeton: str | None) -> list[str]:
    """Les dépôts publics des mêmes propriétaires qui portent des labs hors manifeste."""
    inscrits = {_depot(c["depot"]) for c in catalogues}
    oublies: list[str] = []
    for proprio in sorted({p for p, _ in inscrits}):
        page = 1
        while True:
            depots = _api(f"/users/{proprio}/repos?type=owner&per_page=100&page={page}", jeton)
            if not depots:
                break
            for d in depots:
                if d.get("private") or d.get("archived") or d.get("fork") or (proprio, d["name"]) in inscrits:
                    continue
                if d.get("size", 0) == 0:
                    continue
                chemins = _arbre(proprio, d["name"], d["default_branch"], jeton)
                if "meta.yml" in chemins and _labs(chemins):
                    oublies.append(f"{d['name']} ({_labs(chemins)} labs publiés)")
            page += 1
    return oublies


# ── Écrire la table ──────────────────────────────────────────────────────────


def _table(lang: str, catalogues: list[dict[str, Any]], comptes: dict[str, int]) -> str:
    cat, labs, sujet = EN_TETES[lang]
    publies = [c for c in catalogues if comptes.get(c["depot"], 0) > 0]
    lignes = [f"| {cat} | {labs} | {sujet} |", "|---|---:|---|"]
    for entree in sorted(publies, key=lambda c: (-comptes[c["depot"]], c["depot"])):
        _, depot = _depot(entree["depot"])
        texte = entree[f"description_{lang}"]
        lignes.append(f"| [`{depot}`]({entree['depot']}) | {comptes[entree['depot']]} | {texte} |")
    total = sum(comptes[c["depot"]] for c in publies)
    lignes += ["", PIED[lang].format(labs=total, n=len(publies))]
    return "\n".join(lignes)


def _rendu(chemin: Path, bloc: str) -> str:
    texte = chemin.read_text(encoding="utf-8")
    if DEBUT not in texte or FIN not in texte:
        raise SystemExit(f"{chemin.name} : marqueurs {DEBUT} / {FIN} absents")
    avant = texte[: texte.index(DEBUT) + len(DEBUT)]
    apres = texte[texte.index(FIN):]
    return f"{avant}\n\n{bloc}\n\n{apres}"


def main() -> int:
    analyseur = argparse.ArgumentParser(description=__doc__)
    analyseur.add_argument(
        "--check", action="store_true",
        help="ne réécrit rien ; sort en 1 si un README diffère de la mesure ou si "
             "un catalogue public manque au manifeste, en 2 si rien n'a pu être mesuré",
    )
    arguments = analyseur.parse_args()

    catalogues = _manifeste()
    jeton = _jeton()
    try:
        comptes, ecarts = _mesurer_le_manifeste(catalogues, jeton)
        oublies = _oublies(catalogues, jeton)
    except NonMesurable as e:
        print(f"rien n'a pu être mesuré, donc rien n'est conclu : {e}", file=sys.stderr)
        if not jeton:
            print("   Sans jeton GitHub, l'API limite à 60 appels par heure : "
                  "pose GH_TOKEN, ou connecte `gh auth login`.", file=sys.stderr)
        return 2

    ecarts += [f"{o} : dépôt public avec des labs, absent du manifeste. "
               "Ajoute-le à src/dsoxlab/templates/catalogues.yml" for o in oublies]
    # Un catalogue qui ne publie aucun lab n'a rien à proposer : `catalog list`
    # le montrerait, et l'apprenant qui l'installe tomberait sur un dépôt vide.
    # La 0.9.2 l'écartait de la table sans le refuser au manifeste (certificats,
    # dépôt encore vide le 2026-11-14). Il en sort ; la détection des dépôts
    # oubliés le signalera dès son premier lab publié.
    ecarts += [f"{_depot(c['depot'])[1]} ne publie aucun lab : `dsoxlab catalog list` "
               "le propose pour rien. Retire-le du manifeste jusqu'à son premier lab publié"
               for c in catalogues if comptes.get(c["depot"]) == 0]

    perimes = []
    for nom, lang in CIBLES.items():
        chemin = RACINE / nom
        attendu = _rendu(chemin, _table(lang, catalogues, comptes))
        if chemin.read_text(encoding="utf-8") == attendu:
            continue
        perimes.append(nom)
        if not arguments.check:
            chemin.write_text(attendu, encoding="utf-8")

    for e in ecarts:
        print(f"  ✘ {e}", file=sys.stderr)
    total = sum(comptes.values())
    if arguments.check and perimes:
        print(f"{', '.join(perimes)} : table des catalogues périmée par rapport aux dépôts "
              "publiés. Joue `python3 scripts/gen-catalogues.py`.", file=sys.stderr)
    elif perimes:
        print(f"table régénérée dans {', '.join(perimes)} ({total} labs mesurés)")
    else:
        print(f"table des catalogues à jour ({total} labs mesurés sur {len(comptes)} dépôts publiés)")
    return 1 if ecarts or (arguments.check and perimes) else 0


if __name__ == "__main__":
    sys.exit(main())
